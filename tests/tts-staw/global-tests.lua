test("M5 event ordering is stable by priority and registration",function()
    local events=STA2E.M5.Events;local order={}
    events.on("audit","late",50,function()table.insert(order,"late")end)
    events.on("audit","first",10,function()table.insert(order,"first")end)
    events.on("audit","second",10,function()table.insert(order,"second")end)
    events.emit("audit",{});assert(table.concat(order,",")=="first,second,late")
    events.off("audit","first");order={};events.emit("audit",{});assert(table.concat(order,",")=="second,late")
end)
