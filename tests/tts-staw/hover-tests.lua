local function withAttributes(fn)
    local original=UI.setAttribute;local attributes={};local writes={}
    UI.setAttribute=function(id,key,value)
        attributes[id]=attributes[id] or {};attributes[id][key]=value
        writes[#writes+1]={id=id,key=key,value=value}
        return original(id,key,value)
    end
    local ok,err=pcall(fn,attributes,writes)
    UI.setAttribute=original;assert(ok,tostring(err))
end
local function menu(id,page)
    _reset();local ship=_ship(id,"Blue");ship.state.dialOpen=true
    STA2E_Command({object=_objects[ship.cardGUID],color="Blue",command=page or "tool_home"});_drain()
    return ship,_objects[ship.refs.dial]
end
local function hover(dial,color,id,enter)
    STA2E_DialHover({object=dial,color=color,id=id,enter=enter~=false})
end

test("Dial buttons replace rotated XML tooltips with hover callbacks and preserve clicks",function()
    local ship,dial=menu("hover-hooks")
    local markup=dial._xml
    assert(not markup:find('tooltip="',1,true),"The rotated object tooltip is still enabled")
    for tag in markup:gmatch('<Button[^>]+>') do
        assert(tag:find('onClick="STA2E_UI"',1,true))
        assert(tag:find('onMouseEnter="STA2E_DialHoverEnter"',1,true))
        assert(tag:find('onMouseExit="STA2E_DialHoverExit"',1,true))
        assert(tag:find('onMouseDown="STA2E_DialHoverExit"',1,true))
    end
    local popup=assert(_xml:match('<Panel id="sta2e_hover_Blue".-</Panel></Panel>'))
    assert(popup:find('visibility="Blue"',1,true) and popup:find('rectAlignment="LowerCenter"',1,true))
    assert(popup:find('fontSize="18"',1,true) and popup:find('horizontalOverflow="Wrap"',1,true))
    assert(not popup:find('rotation=',1,true) and not popup:find('scale=',1,true))
    assert(not popup:find('raycastTarget="true"',1,true),"Popup can block controls")
end)

test("Dial hover displays readable help after a short delay and hides on exit",function()
    local ship,dial=menu("hover-delay")
    withAttributes(function(attributes,writes)
        hover(dial,"Blue","tool_moves")
        assert(attributes.sta2e_hover_Blue.active=="false")
        _drain()
        assert(attributes.sta2e_hover_Blue.active=="true")
        assert(attributes.sta2e_hover_text_Blue.text=="Choose an immediate maneuver without changing the planned maneuver.")
        assert(not attributes.sta2e_hover_Red,"Help leaked to another player")
        hover(dial,"Blue","tool_moves",false)
        assert(attributes.sta2e_hover_Blue.active=="false")
    end)
end)

test("Late exits do not hide the tooltip for a newer button",function()
    local ship,dial=menu("hover-race")
    withAttributes(function(attributes)
        hover(dial,"Blue","tool_moves")
        hover(dial,"Blue","tool_arcs")
        hover(dial,"Blue","tool_moves",false)
        _drain()
        assert(attributes.sta2e_hover_Blue.active=="true")
        assert(attributes.sta2e_hover_text_Blue.text=="Open range guides, firing arcs, and ship measurements.")
        hover(dial,"Blue","tool_arcs",false)
    end)
end)

test("Private maneuver hover help is restricted to the owning player",function()
    local ship,dial=menu("hover-private","tool_phase")
    withAttributes(function(attributes,writes)
        hover(dial,"Red","select_S1");_drain()
        assert(#writes==0,"A hidden planning control responded for a different player")
        hover(dial,"Blue","select_S1");_drain()
        assert(attributes.sta2e_hover_Blue.active=="true")
        assert(attributes.sta2e_hover_text_Blue.text:find("Select Straight 1",1,true))
        assert(not attributes.sta2e_hover_Red)
        hover(dial,"Blue","select_S1",false)
    end)
end)

test("Shared tools allow independent hover help for two players",function()
    local ship,dial=menu("hover-multiplayer")
    withAttributes(function(attributes)
        hover(dial,"Blue","tool_moves");hover(dial,"Red","tool_tokens");_drain()
        assert(attributes.sta2e_hover_Blue.active=="true" and attributes.sta2e_hover_Red.active=="true")
        assert(attributes.sta2e_hover_text_Blue.text~=attributes.sta2e_hover_text_Red.text)
        hover(dial,"Blue","tool_moves",false)
        assert(attributes.sta2e_hover_Red.active=="true")
        hover(dial,"Red","tool_tokens",false)
    end)
end)

test("Closing or changing the dial cancels pending hover popups",function()
    local ship,dial=menu("hover-close")
    withAttributes(function(attributes)
        hover(dial,"Blue","tool_moves")
        STA2E_Command({object=_objects[ship.cardGUID],color="Blue",command="open_dial"});_drain()
        assert(dial._xml=="" and attributes.sta2e_hover_Blue.active=="false")
    end)
end)

test("Special maneuver descriptions remain available in the upright popup",function()
    local ship,dial=menu("hover-special","tool_moves")
    STA2E_Command({object=_objects[ship.cardGUID],color="Blue",command="tool_next"});_drain()
    withAttributes(function(attributes)
        hover(dial,"Blue","tool_move_FAL1");_drain()
        assert(attributes.sta2e_hover_text_Blue.text:find("Execute Full About Left 1",1,true))
        hover(dial,"Blue","tool_move_IRR1");_drain()
        assert(attributes.sta2e_hover_text_Blue.text:find("Execute Impulse Roll Right 1",1,true))
        hover(dial,"Blue","tool_move_IRR1",false)
    end)
end)

test("Packaged object hover callbacks route to Global and retain the original click action",function()
    local ship,dial=menu("hover-member-bridge")
    local environment=setmetatable({self=dial},{__index=_G})
    assert(load(MEMBER_SCRIPT,"member-hover-bridge","t",environment))()
    withAttributes(function(attributes)
        environment.STA2E_DialHoverEnter(Player.Blue,"-1","tool_tokens");_drain()
        assert(attributes.sta2e_hover_Blue.active=="true")
        environment.STA2E_DialHoverExit(Player.Blue,"-1","tool_tokens")
        assert(attributes.sta2e_hover_Blue.active=="false")
        environment.STA2E_UI(Player.Blue,"","tool_tokens");_drain()
        assert(ship.state.toolsPage=="tokens")
    end)
end)
